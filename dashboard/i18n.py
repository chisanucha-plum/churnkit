def get_language() -> str:
    return st.session_state.get("lang", DEFAULT_LANG)


def set_language(lang: str) -> None:
    st.session_state["lang"] = lang


def t(key: str) -> str:
    lang = get_language()
    lang_table = TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANG])
    return lang_table.get(key, TRANSLATIONS[DEFAULT_LANG].get(key, key))


def render_language_selector() -> None:
    options = ["English", "ไทย"]
    values = ["en", "th"]
    current = get_language()
    index = values.index(current) if current in values else 0
    choice = st.selectbox(t("language_label"), options, index=index)
    set_language(values[options.index(choice)])
